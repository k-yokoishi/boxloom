"""Generate editor-visible Python constants from the vanilla registry snapshot."""

import argparse
import json
from pathlib import Path
import re
import sys
from typing import Dict


SDK_ROOT = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = SDK_ROOT.parent.parent
SNAPSHOT = REPOSITORY_ROOT / "data/minecraft/registries.json"


def render_modules(snapshot: object, expected_version: str) -> Dict[str, str]:
    if not isinstance(snapshot, dict) or snapshot.get("minecraft_version") != expected_version:
        raise ValueError(
            "Registry snapshot does not match server/gradle.properties; "
            "run mise run python-generate-constants"
        )

    modules = {}
    for registry in ("blocks", "entities"):
        identifiers = snapshot.get(registry)
        if not isinstance(identifiers, list) or not identifiers:
            raise ValueError(f"{registry} must be a non-empty list of vanilla IDs")

        constants = {}
        for identifier in identifiers:
            if not isinstance(identifier, str) or not re.fullmatch(
                r"minecraft:[a-z0-9_./-]+", identifier
            ):
                raise ValueError(f"Invalid vanilla {registry} ID: {identifier!r}")
            name = re.sub(r"[^A-Z0-9_]", "_", identifier.split(":", 1)[1].upper())
            if not name.isidentifier() or name.startswith("_") or name == "MINECRAFT_VERSION":
                raise ValueError(f"Cannot generate a constant for {identifier!r}")
            if name in constants:
                raise ValueError(f"Duplicate {registry} constant {name}: {identifier!r}")
            constants[name] = identifier

        label = "block" if registry == "blocks" else "entity type"
        lines = [
            f'"""Vanilla Minecraft {expected_version} {label} IDs for editor completion.',
            "",
            "Generated by mise run python-generate-constants. Do not edit by hand.",
            '"""',
            "",
            "from typing import Final as _Final",
            "",
            f"MINECRAFT_VERSION: _Final[str] = {json.dumps(expected_version)}",
            "",
        ]
        lines.extend(
            f"{name}: _Final[str] = {json.dumps(identifier)}"
            for name, identifier in sorted(constants.items())
        )
        modules[registry] = "\n".join(lines) + "\n"
    return modules


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files are stale")
    args = parser.parse_args()

    properties = (REPOSITORY_ROOT / "server/gradle.properties").read_text(encoding="utf-8")
    version = re.search(r"^minecraft_version=(.+)$", properties, re.MULTILINE)
    if version is None:
        parser.error("minecraft_version is missing from server/gradle.properties")
    try:
        modules = render_modules(
            json.loads(SNAPSHOT.read_text(encoding="utf-8")), version.group(1).strip()
        )
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")

    stale = []
    for name, content in modules.items():
        output = SDK_ROOT / "src/boxloom" / f"{name}.py"
        if args.check:
            if not output.exists() or output.read_text(encoding="utf-8") != content:
                stale.append(str(output.relative_to(REPOSITORY_ROOT)))
        else:
            output.write_text(content, encoding="utf-8")

    if stale:
        print("Out-of-date constants: " + ", ".join(stale), file=sys.stderr)
        print("Run mise run python-generate-constants", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
